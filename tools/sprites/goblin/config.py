def foreground(c):
    """Everything that isn't the blue background."""
    r, g, b = c[..., 0], c[..., 1], c[..., 2]
    return ~((b > 150) & (r < 90) & (g < 110) & (b > r + 100))


def isskin(c):   # his yellow-green skin, for anchoring on the body
    r, g, b = c[..., 0], c[..., 1], c[..., 2]
    return (g > 120) & (r > 90) & (b < 90)
