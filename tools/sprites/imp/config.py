def foreground(c):
    """Everything that isn't the green screen (keeps the green-tinged fire edges out too)."""
    r, g, b = c[..., 0], c[..., 1], c[..., 2]
    return ~((g > r + 60) & (g > b + 60))


def isred(c): return (c[..., 0] > 120) & (c[..., 1] < 90) & (c[..., 2] < 90)
